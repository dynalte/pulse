export function EmojiPicker({ onPick, onClose }: { onPick: (emoji: string) => void; onClose?: () => void }) {
  const [cat, setCat] = useState(CATEGORIES[0].key);
  const active = CATEGORIES.find((c) => c.key === cat) || CATEGORIES[0];
  return (
    <div className="emoji-picker" role="dialog" aria-label="Choisir un emoji">
      <div className="emoji-cats">
        {CATEGORIES.map((c) => (
          <button
            key={c.key}
            type="button"
            className={c.key === cat ? 'active' : ''}
            onClick={() => setCat(c.key)}
            aria-label={`Catégorie ${c.key}`}
          >
            {c.label}
          </button>
        ))}
        {onClose && (
          <button type="button" className="emoji-close" onClick={onClose} aria-label="Fermer">✕</button>
        )}
      </div>
      <div className="emoji-grid">
        {active.emojis.map((e, i) => (
          <button key={`${e}-${i}`} type="button" onClick={() => onPick(e)} aria-label={`Emoji ${e}`}>
            {e}
          </button>
        ))}
      </div>
    </div>
  );
}

